--11. Retrieve product names along with their total sales using a JOIN.


	select 
	   p.product_name ,
	   sum(s.sales) as total_sales
	   from product p 
	   inner join sales s 
	   on p.product_id = s.product_id
	   group by  p.product_name
	   order by p.product_name asc



   --12. Find the total quantity sold for each product category.

	 select 
	   p.category ,
	   sum(s.quantity) as total_quantity
	   from product p 
	   inner join sales s 
	   on p.product_id = s.product_id
	   group by  p.category
	   order by p.category asc



   --13. Identify customers who have never placed an order.
	
	   SELECT
	    c.Customer_id,
	    c.Customer_name,
	    c.Segment,
	    c.City,
	    c.Region
