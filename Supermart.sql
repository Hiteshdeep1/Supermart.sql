 --17. Identify customers whose total sales are greater than the average customer sales.*


		 SELECT
		    c.Customer_id,
		    c.Customer_name,
		    SUM(s.Sales) AS Total_Sales
		FROM customer c
		JOIN sales s
		    ON c.Customer_id = s.Customer_id
		GROUP BY c.Customer_id, c.Customer_name
		HAVING SUM(s.Sales) > (
		    SELECT AVG(customer_sales)
		    FROM (
		        SELECT SUM(Sales) AS customer_sales
		        FROM sales
		        GROUP BY Customer_id
		    ) AS avg_sales
		)
		ORDER BY Total_Sales DESC;


--18. Rank the top 5 products by total profit within each category using a window function.

	       WITH Product_Profit AS (
	    SELECT
	        p.Category,
	        p.Product_id,
	        p.Product_name,
	        SUM(s.Profit) AS Total_Profit
	    FROM product p
	    INNER JOIN sales s
	        ON p.Product_id = s.Product_id
	    GROUP BY
	        p.Category,
	        p.Product_id,
	        p.Product_name
	),
	Ranked_Products AS (
	    SELECT
	        Category,
	        Product_id,
	        Product_name,
	        Total_Profit,
	        DENSE_RANK() OVER (
	            PARTITION BY Category
	            ORDER BY Total_Profit DESC
	        ) AS Profit_Rank
	    FROM Product_Profit
	)
	SELECT
	    Category,
	    Product_id,
	    Product_name,
	    Total_Profit,
	    Profit_Rank
	FROM Ranked_Products
	WHERE Profit_Rank <= 5
	ORDER BY Category, Profit_Rank;


--19. Calculate the running total of sales based on order date.

	SELECT
	    Order_date,
	    Order_id,
	    Sales,
	    SUM(Sales) OVER (
	        ORDER BY Order_date, Order_id
	        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
	    ) AS Running_Total_Sales
	FROM sales
	ORDER BY Order_date, Order_id;


--20. Calculate each region's percentage contribution to overall sales using a CTE or subquery.

		WITH Region_Sales AS (
	    SELECT
	        c.Region,
	        SUM(s.Sales) AS Total_Sales
	    FROM customer c
	    INNER JOIN sales s
	        ON c.Customer_id = s.Customer_id
	    GROUP BY c.Region
	)
	SELECT
	    Region,
	    Total_Sales,
	    ROUND(
	        (Total_Sales * 100.0 / SUM(Total_Sales) OVER ()),
	        2
	    ) AS Sales_Percentage
	FROM Region_Sales
	ORDER BY Sales_Percentage DESC;
	
	
 

 
 

 