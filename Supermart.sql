 -- 1. Retrieve all records from the customer table.

 select * from customer



 --2. Display all unique customer segments from the customer table.


 select DISTINCT (segment) from customer


 --3. Find the total number of customers in each region.

 select region , count(*) as num_cust
 from customer
 group by region 
 having count(*)>1


 --4. Retrieve all products belonging to the Technology category.

 select * from product

 select product_name from product 
 where category= 'Technology'


 --5. Find the total number of products in each category.

 select category , count(*) as TOTAL_product
 from product
 group by category
 having count(*) >1

 --6. Display all sales records where the profit is greater than 500.

 
 select * from sales

 select * from sales 
 where profit>500

 --7. Find all orders placed between January 1, 2023, and December 31, 2023.

 select * from sales 
 where order_date >= '2023-01-01' 
 and order_date< '2023-12-31'


 --8. Find the total sales and total profit generated by each region.

select 
   c.region,
   sum(s.sales) as total_sales,
   sum(s.profit) as total_profit
   from customer c
   inner join sales s
    on s.customer_id= c.customer_id
	 group by c.region 
	 order by total_sales desc



--9. Calculate the average discount given on sales transactions.


select avg(discount) from sales


--10. Find the top 10 customers based on total sales.

select sales from sales
order by sales desc
